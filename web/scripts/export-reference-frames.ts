/**
 * Renders reference frames with the TypeScript engine for the firmware's native
 * engine test. Writes a C++ header with one JSON case per animation and LED count.
 *
 *   npm run fixtures
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { cycleMs, render } from '../src/animation/engine'
import { parseAnimation } from '../src/animation/format'
import type { Animation } from '../src/animation/types'
import type { RGB } from '../src/types'

const root = resolve(import.meta.dirname, '../..')
const animationsDir = join(root, 'animations')
const outFile = join(root, 'firmware/test/fixtures/reference_frames.h')

const LED_COUNTS = [48, 24]
const TIME_FRACTIONS = [0, 0.13, 0.37, 0.5, 0.61, 0.89]
/** Free-running layers follow a clock that is far from the loop time. */
const CLOCK_OFFSET_MS = 987_654

const red = { r: 255, g: 0, b: 0 }
const green = { r: 0, g: 255, b: 0 }
const blue = { r: 0, g: 0, b: 255 }
const white = { r: 255, g: 255, b: 255 }
const base = { blend: 'normal', opacity: 1, speed: 1, hidden: false, mirror: false } as const

/** Cases that exercise engine features the committed animations don't cover. */
const synthetic: Animation[] = [
  {
    version: 1,
    name: 'synthetic: hard bands backward at x2',
    loopMs: 3000,
    layers: [{ ...base, speed: 2, generator: 'bands', params: { colors: [red, green, blue], edge: 'hard', repeat: 3, scroll: -1 } }],
  },
  {
    version: 1,
    name: 'synthetic: smooth bands at x0.5',
    loopMs: 2500,
    layers: [{ ...base, speed: 0.5, generator: 'bands', params: { colors: [red, white], edge: 'smooth', repeat: 2, scroll: 1 } }],
  },
  {
    version: 1,
    name: 'synthetic: add and opacity',
    loopMs: 4000,
    layers: [
      { ...base, generator: 'solid', params: { color: { r: 40, g: 10, b: 90 } } },
      { ...base, blend: 'add', opacity: 0.6, generator: 'bands', params: { colors: [red, green, blue, white], edge: 'smooth', repeat: 1, scroll: 1 } },
      { ...base, opacity: 0.3, speed: 4, generator: 'bands', params: { colors: [blue, red], edge: 'hard', repeat: 5, scroll: 0 } },
      { ...base, hidden: true, generator: 'solid', params: { color: white } },
    ],
  },
]

function committed(): Animation[] {
  return readdirSync(animationsDir)
    .filter(f => f.endsWith('.json'))
    .sort()
    .map(f => {
      const result = parseAnimation(JSON.parse(readFileSync(join(animationsDir, f), 'utf8')))
      if (!result.ok) throw new Error(`${f}: ${result.errors.join('; ')}`)
      return result.animation
    })
}

const hex = (leds: RGB[]) => leds.map(c => [c.r, c.g, c.b].map(v => v.toString(16).padStart(2, '0')).join('')).join('')

function cases(animation: Animation) {
  const cycle = cycleMs(animation)
  const times = [...TIME_FRACTIONS.map(f => Math.round(f * cycle)), cycle + Math.round(animation.loopMs / 4)]
  return LED_COUNTS.map(ledCount => ({
    name: animation.name,
    ledCount,
    animation,
    frames: times.map(timeMs => {
      const clockMs = timeMs + CLOCK_OFFSET_MS
      return { timeMs, clockMs, leds: hex(render(animation, timeMs, ledCount, clockMs)) }
    }),
  }))
}

const all = [...committed(), ...synthetic].flatMap(cases)
const body = all.map(c => `  R"FIXTURE(${JSON.stringify(c)})FIXTURE"`).join(',\n')
writeFileSync(
  outFile,
  `// Generated by web/scripts/export-reference-frames.ts (npm run fixtures). Do not edit.
#pragma once

static const char* const kReferenceCases[] = {
${body},
};

static const int kReferenceCaseCount = ${all.length};
`,
)
console.log(`Wrote ${all.length} cases to ${outFile}`)
